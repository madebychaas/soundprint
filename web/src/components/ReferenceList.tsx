"use client";

/**
 * Project reference list with live status.
 *
 * Polls only while something is actually in flight, then stops. A dashboard
 * that keeps hitting the server after everything has settled is a bug, not a
 * feature.
 */

import Link from "next/link";
import { useRouter } from "next/navigation";
import { useCallback, useEffect, useState } from "react";

import { RatingControl } from "./RatingControl";

export interface ReferenceRow {
  id: string;
  title: string;
  artist: string | null;
  filename: string;
  status: string;
  statusDetail: string | null;
  error: string | null;
  durationSeconds: number | null;
  rating: string | null;
  bpm: number | null;
  key: string | null;
  mode: string | null;
  keyAmbiguous: boolean;
  heuristic: boolean | null;
  warnings: number;
}

const ACTIVE = new Set(["uploaded", "analyzing", "interpreting"]);

function formatDuration(s: number | null) {
  if (s === null) return "—";
  const m = Math.floor(s / 60);
  return `${m}:${String(Math.round(s % 60)).padStart(2, "0")}`;
}

export function ReferenceList({
  projectId,
  initial,
}: {
  projectId: string;
  initial: ReferenceRow[];
}) {
  const router = useRouter();
  const [rows, setRows] = useState(initial);

  // Server-rendered props win on navigation/refresh.
  useEffect(() => setRows(initial), [initial]);

  const anyActive = rows.some((r) => ACTIVE.has(r.status));

  const poll = useCallback(async () => {
    const active = rows.filter((r) => ACTIVE.has(r.status));
    if (active.length === 0) return;

    const updates = await Promise.all(
      active.map((r) =>
        fetch(`/api/references/${r.id}`)
          .then((res) => (res.ok ? res.json() : null))
          .catch(() => null),
      ),
    );

    let settled = false;
    setRows((prev) =>
      prev.map((row) => {
        const u = updates.find((x) => x?.id === row.id);
        if (!u) return row;
        if (!ACTIVE.has(u.status)) settled = true;
        return { ...row, status: u.status, statusDetail: u.statusDetail, error: u.error };
      }),
    );

    // Pull the full server-rendered row once analysis lands, so BPM and key appear.
    if (settled) router.refresh();
  }, [rows, router]);

  useEffect(() => {
    if (!anyActive) return;
    const timer = setInterval(poll, 1500);
    return () => clearInterval(timer);
  }, [anyActive, poll]);

  if (rows.length === 0) {
    return (
      <div className="rounded border border-dashed border-line px-6 py-16 text-center">
        <p className="text-[13px] text-ink-2">No references yet.</p>
        <p className="mt-1 text-[12px] text-ink-4">
          Upload a track to see what it is actually doing.
        </p>
      </div>
    );
  }

  return (
    <div className="overflow-hidden rounded border border-line">
      <table className="w-full">
        <thead>
          <tr className="border-b border-line bg-surface text-left">
            <th className="eyebrow px-4 py-2.5 font-medium">Reference</th>
            <th className="eyebrow px-3 py-2.5 font-medium">Tempo</th>
            <th className="eyebrow px-3 py-2.5 font-medium">Key</th>
            <th className="eyebrow px-3 py-2.5 font-medium">Length</th>
            <th className="eyebrow px-3 py-2.5 font-medium">Rating</th>
          </tr>
        </thead>
        <tbody className="divide-y divide-line">
          {rows.map((row) => {
            const active = ACTIVE.has(row.status);
            const failed = row.status === "failed";
            return (
              <tr key={row.id} className="group transition-colors hover:bg-surface/60">
                <td className="px-4 py-3">
                  <Link href={`/references/${row.id}`} className="block">
                    <div className="flex items-center gap-2">
                      <StatusDot status={row.status} />
                      <span className="truncate text-[13.5px] font-medium group-hover:text-signal">
                        {row.title}
                      </span>
                      {row.heuristic && (
                        <span
                          title="Sound DNA generated by built-in rules, not a language model"
                          className="rounded border border-warn/40 px-1.5 py-px text-[9.5px] uppercase tracking-wide text-warn"
                        >
                          rules
                        </span>
                      )}
                      {row.warnings > 0 && (
                        <span
                          title={`${row.warnings} analysis caveat(s)`}
                          className="tnum text-[10px] text-warn"
                        >
                          ⚑{row.warnings}
                        </span>
                      )}
                    </div>
                    <div className="mt-0.5 truncate text-[11px] text-ink-4">
                      {active
                        ? (row.statusDetail ?? "Working…")
                        : failed
                          ? (row.error ?? "Analysis failed")
                          : (row.artist ?? row.filename)}
                    </div>
                  </Link>
                </td>
                <td className="tnum px-3 py-3 text-[12.5px] text-ink-2">
                  {row.bpm ? `${Math.round(row.bpm)}` : active ? "…" : "—"}
                </td>
                <td className="px-3 py-3 text-[12.5px] text-ink-2">
                  {row.key ? (
                    <span className={row.keyAmbiguous ? "text-warn" : undefined}>
                      {row.key} {row.mode}
                      {row.keyAmbiguous && <span title="Key estimate is ambiguous">?</span>}
                    </span>
                  ) : active ? (
                    "…"
                  ) : (
                    "—"
                  )}
                </td>
                <td className="tnum px-3 py-3 text-[12.5px] text-ink-3">
                  {formatDuration(row.durationSeconds)}
                </td>
                <td className="px-3 py-3">
                  <RatingControl referenceId={row.id} initial={row.rating} compact />
                </td>
              </tr>
            );
          })}
        </tbody>
      </table>
    </div>
  );
}

function StatusDot({ status }: { status: string }) {
  const map: Record<string, { cls: string; label: string }> = {
    uploaded: { cls: "bg-ink-4 animate-working", label: "Queued" },
    analyzing: { cls: "bg-signal animate-working", label: "Analyzing" },
    interpreting: { cls: "bg-info animate-working", label: "Interpreting" },
    complete: { cls: "bg-good", label: "Complete" },
    partial: { cls: "bg-warn", label: "Partial" },
    failed: { cls: "bg-bad", label: "Failed" },
  };
  const s = map[status] ?? map.uploaded;
  return <span title={s.label} className={`h-1.5 w-1.5 shrink-0 rounded-full ${s.cls}`} />;
}
