/**
 * Deterministic interpretation — no LLM, no network.
 *
 * Two reasons this exists:
 *
 *  1. Soundprint must do something useful on a machine with no API key and no
 *     network. A tool that shows an error screen until you configure billing
 *     has failed the person evaluating it.
 *  2. Reference audio may be unreleased. Some users will never want derived
 *     data leaving the machine, and this path guarantees it does not.
 *
 * It maps observations onto DNA fields with rules. It is genuinely weaker than
 * a model at the interpretive layer — it can describe mechanisms it has rules
 * for and nothing else — so every result it produces is marked `heuristic:
 * true` and the UI labels it. It must never be mistaken for AI interpretation.
 *
 * Where it has no rule, it writes null. That is the same contract the model is
 * held to.
 */

import type { ObjectiveAnalysis, Observation } from "../analysis/types";
import { formatTime } from "../analysis/types";
import { type Claim, type SoundDna, emptyDna } from "../dna/schema";
import type {
  InterpretationProvider,
  InterpretationRequest,
  InterpretationResult,
  ProviderAvailability,
} from "./provider";

const has = (obs: Observation[], id: string) => obs.some((o) => o.id === id);
const get = (obs: Observation[], id: string) => obs.find((o) => o.id === id);

function claim(text: string, evidence: string[], confidence: number): Claim {
  return { claim: text, evidence, confidence };
}

export class HeuristicProvider implements InterpretationProvider {
  readonly id = "heuristic";
  readonly label = "Built-in rules (no AI)";
  readonly requiresNetwork = false;

  async availability(): Promise<ProviderAvailability> {
    return { id: this.id, label: this.label, available: true, requiresNetwork: false };
  }

  async interpret(request: InterpretationRequest): Promise<InterpretationResult> {
    return {
      dna: buildHeuristicDna(request.analysis, request.metadata, request.userNotes),
      provider: this.id,
      model: null,
      heuristic: true,
      issues: [
        "Generated by built-in rules, not a language model. Interpretation is limited to patterns Soundprint has explicit rules for.",
      ],
    };
  }
}

export function buildHeuristicDna(
  a: ObjectiveAnalysis,
  metadata: { title: string; artist: string | null; filename: string },
  userNotes: string[] = [],
): SoundDna {
  const dna = emptyDna();
  const obs = a.observations;

  dna.metadata = {
    title: metadata.title || null,
    artist: metadata.artist,
    source_filename: metadata.filename,
    duration_seconds: a.metadata.duration_seconds,
  };

  // ------------------------------------------------------------------ tempo
  const halfTime = (a.tempo.half_time_feel_likelihood ?? 0) > 0.55;
  const doubleTime = (a.tempo.double_time_feel_likelihood ?? 0) > 0.55;
  dna.tempo = {
    bpm: a.tempo.bpm,
    confidence: a.tempo.confidence,
    perceived_speed: a.tempo.bpm
      ? halfTime
        ? `Feels slower than ${Math.round(a.tempo.bpm)} BPM — closer to ${Math.round(a.tempo.bpm / 2)} BPM in the body`
        : doubleTime
          ? `Feels faster than ${Math.round(a.tempo.bpm)} BPM because of dense subdivision`
          : `Broadly matches its ${Math.round(a.tempo.bpm)} BPM`
      : null,
    feel: halfTime
      ? "Half-time: the backbeat lands once per bar rather than twice"
      : a.rhythm.onset_density_per_beat !== null
        ? a.rhythm.onset_density_per_beat < 1.0
          ? "Spacious — noticeable air between rhythmic events"
          : a.rhythm.onset_density_per_beat > 3
            ? "Busy and continuous"
            : "Steady and even"
        : null,
    meter: a.tempo.meter.label,
    notes:
      (a.tempo.confidence ?? 1) < 0.5
        ? "Tempo confidence is low; half or double this value may be the better reading."
        : null,
  };

  // ----------------------------------------------------------------- rhythm
  dna.rhythm = {
    groove: has(obs, "rhythm.offbeat_driven")
      ? "Driven from the upbeats"
      : halfTime
        ? "Held back — the groove leaves space rather than filling it"
        : null,
    syncopation:
      a.rhythm.syncopation_index === null
        ? null
        : a.rhythm.syncopation_index > 0.45
          ? "High — events frequently land off the grid"
          : a.rhythm.syncopation_index < 0.2
            ? "Low — events sit on the grid"
            : "Moderate",
    swing:
      a.rhythm.swing_ratio === null
        ? null
        : a.rhythm.swing_ratio > 1.25
          ? `Swung, roughly ${a.rhythm.swing_ratio.toFixed(2)}:1`
          : "Straight",
    drum_density:
      a.rhythm.onset_density_per_beat === null
        ? null
        : a.rhythm.onset_density_per_beat < 1.0
          ? "Sparse"
          : a.rhythm.onset_density_per_beat > 3
            ? "Dense"
            : "Moderate",
    percussion_character: [
      has(obs, "rhythm.percussion_forward") ? "percussion-forward" : null,
      has(obs, "rhythm.low_percussive") ? "restrained percussion" : null,
      has(obs, "rhythm.offbeat_driven") ? "offbeat emphasis" : null,
    ].filter((v): v is string => v !== null),
    notes: null,
  };

  // ---------------------------------------------------------------- harmony
  dna.harmony = {
    key: a.tonal.key,
    mode: a.tonal.mode,
    tonality: a.tonal.key_ambiguous
      ? "Ambiguous — consistent with modal or static-harmony writing"
      : a.tonal.mode === "minor"
        ? "Minor-centred"
        : a.tonal.mode === "major"
          ? "Major-centred"
          : null,
    harmonic_density:
      a.tonal.harmonic_change_rate === null
        ? null
        : a.tonal.harmonic_change_rate < 0.12
          ? "Very static — long stretches on one harmony"
          : a.tonal.harmonic_change_rate > 0.6
            ? "Active — frequent harmonic movement"
            : "Moderate",
    chord_movement: has(obs, "harmony.static")
      ? "Minimal; the interest is not coming from harmonic motion"
      : null,
    tension_character: has(obs, "harmony.shifting_centre")
      ? "The tonal centre shifts across the track"
      : null,
    notes: a.tonal.key_ambiguous
      ? `Key estimate is uncertain. Alternates: ${a.tonal.alternates.slice(0, 2).join(", ")}.`
      : null,
  };

  // ------------------------------------------------------------------- bass
  const lowEnd = a.bass.low_end_ratio;
  dna.bass = {
    prominence:
      lowEnd === null
        ? null
        : lowEnd > 0.55
          ? "Dominant — the low end carries the track"
          : lowEnd < 0.18
            ? "Light — little weight below 250 Hz"
            : "Balanced",
    frequency_character: has(obs, "bass.sub_heavy")
      ? "Sub-weighted; energy sits in the felt rather than heard register"
      : a.bass.sub_extension_hz && a.bass.sub_extension_hz > 70
        ? `Limited extension — little sustained energy below ${Math.round(a.bass.sub_extension_hz)} Hz`
        : null,
    movement: has(obs, "bass.static")
      ? "Static — closer to a sustained root than a moving line"
      : has(obs, "bass.mobile")
        ? "Mobile — an active, melodic low end"
        : null,
    relationship_to_drums: has(obs, "bass.locked_to_beat")
      ? "Locked tightly to the beat grid"
      : null,
    notes: null,
  };

  // ----------------------------------------------------------------- vocals
  // Deliberately thin. Without separation there is nothing honest to say
  // beyond presence, so delivery/register/processing stay null.
  dna.vocals = {
    presence:
      a.vocals.presence_likelihood === null
        ? null
        : a.vocals.presence_likelihood > 0.6
          ? "Vocal-range activity is likely present (unconfirmed)"
          : a.vocals.presence_likelihood < 0.25
            ? "Little vocal-range activity; possibly instrumental (unconfirmed)"
            : "Inconclusive",
    detection_confidence: a.vocals.confidence,
    delivery: null,
    register: null,
    processing: [],
    layering: null,
    intimacy: null,
    notes: a.vocals.note,
  };

  // ------------------------------------------------------------- production
  dna.production = {
    density: has(obs, "structure.high_contrast")
      ? "Varies sharply between sections"
      : has(obs, "structure.low_contrast")
        ? "Held consistent throughout"
        : null,
    stereo_width: !a.stereo.available
      ? "Not measurable — mono or dual-mono source"
      : a.stereo.width_index === null
        ? null
        : a.stereo.width_index > 0.3
          ? "Wide"
          : a.stereo.width_index < 0.06
            ? "Narrow, centre-focused"
            : "Moderate",
    space: has(obs, "stereo.width_changes")
      ? "Width is used as an arrangement device rather than set once"
      : null,
    reverb_character: null, // not measurable without deconvolution
    compression_character:
      a.dynamics.crest_factor_db === null
        ? null
        : a.dynamics.crest_factor_db < 8
          ? "Heavily compressed or limited"
          : a.dynamics.crest_factor_db > 16
            ? "Open — transients largely intact"
            : "Moderately controlled",
    texture: [
      has(obs, "spectral.noisy") ? "noise-forward" : null,
      has(obs, "spectral.tonal") ? "strongly pitched" : null,
      has(obs, "spectral.static_texture") ? "constant timbral palette" : null,
      has(obs, "spectral.rolled_off_top") ? "rolled-off top end" : null,
    ].filter((v): v is string => v !== null),
    distortion: null, // cannot be separated from noisy source material
    warmth_brightness:
      a.spectral.brightness_index === null
        ? null
        : a.spectral.brightness_index < 0.2
          ? "Dark"
          : a.spectral.brightness_index > 0.6
            ? "Bright"
            : "Balanced",
    polish: a.dynamics.clipping_detected ? "Pushed into the ceiling" : null,
    notes: null,
  };

  // --------------------------------------------------------------- dynamics
  dna.dynamics = {
    dynamic_range:
      a.dynamics.loudness_range_db === null
        ? null
        : `${a.dynamics.loudness_range_db.toFixed(1)} dB between quiet and loud passages`,
    crest_character:
      a.dynamics.crest_factor_db === null
        ? null
        : `Crest factor ${a.dynamics.crest_factor_db.toFixed(1)} dB`,
    loudness_impression:
      a.dynamics.integrated_loudness_lufs_approx === null
        ? null
        : `Approximately ${a.dynamics.integrated_loudness_lufs_approx.toFixed(1)} LUFS (estimate)`,
    contrast: has(obs, "structure.high_contrast")
      ? "Built on strong section-to-section contrast"
      : has(obs, "structure.low_contrast")
        ? "Deliberately consistent"
        : null,
    notes: null,
  };

  // ------------------------------------------------------------- arrangement
  dna.arrangement = {
    sections: a.structure.segments.map((s) => ({
      label: s.label,
      start: s.start,
      end: s.end,
      // Functional roles need musical judgement this layer does not have.
      likely_role: null,
      role_confidence: null,
      character: s.character,
    })),
    intro_character: has(obs, "structure.sparse_opening")
      ? "Deliberately sparse; withholds weight"
      : null,
    verse_character: null,
    pre_hook_character: null,
    hook_character: null,
    bridge_character: null,
    outro_character: null,
    density_trajectory: has(obs, "structure.delayed_peak")
      ? "Withholds density, delivering it late"
      : null,
    energy_trajectory: a.timeline.energy_trajectory_shape,
    transition_style: has(obs, "structure.largest_lift")
      ? "Step changes between sections rather than gradual blending"
      : null,
    notes: a.structure.reliable
      ? null
      : (a.structure.note ??
        "Structural segmentation was not reliable for this track."),
  };

  // ---------------------------------------------------------------- emotion
  // Emotion is not measurable. Only the two dimensions with a defensible
  // acoustic correlate are filled; everything else stays null.
  dna.emotion = {
    primary: [],
    secondary: [],
    valence:
      a.tonal.mode === "minor" && !a.tonal.key_ambiguous
        ? "Minor tonality, conventionally read as darker"
        : a.tonal.mode === "major" && !a.tonal.key_ambiguous
          ? "Major tonality, conventionally read as brighter"
          : null,
    intensity:
      a.dynamics.loudness_range_db === null
        ? null
        : a.dynamics.loudness_range_db > 16
          ? "Varies substantially across the track"
          : "Broadly consistent",
    narrative_arc: a.timeline.energy_trajectory_shape,
    notes:
      "Emotional character is not directly measurable. These entries reflect only conventional associations of measured properties.",
  };

  dna.signature_traits = topTraits(obs);

  // ---------------------------------------------------- creative interpretation
  const mechanisms = buildMechanisms(a, obs);
  dna.creative_interpretation = {
    what_makes_it_work: mechanisms,
    what_creates_tension: tensionClaims(obs),
    what_creates_release: releaseClaims(obs),
    most_distinctive_choices: obs
      .filter((o) => o.salience >= 0.8)
      .slice(0, 4)
      .map((o) => claim(o.text, [o.id], o.salience)),
    what_not_to_copy: [
      "The specific melody and any lyric content of this recording",
      "The exact chord sequence where it is distinctive",
      "Any recognisable signature hook or production stamp unique to this track",
      "The identity or vocal likeness of the performing artist",
    ],
  };

  dna.why_this_works = {
    summary: buildWhySummary(a, obs, userNotes),
    mechanisms,
  };

  dna.generation_guidance = buildGuidance(a, obs);

  const unmeasurable = [
    "Instrumentation — the analysis measures frequency bands, not instruments",
    "Reverb character — not separable without deconvolution",
    "Lyrical or melodic content",
  ];
  if (!a.stereo.available) unmeasurable.push("Stereo imaging — source is mono or dual-mono");
  if ((a.vocals.confidence ?? 0) < 0.5) unmeasurable.push("Vocal treatment — no source separation");

  dna.uncertainty = {
    unmeasurable,
    low_confidence_areas: [
      ...(a.tonal.key_ambiguous ? ["Key and mode"] : []),
      ...(!a.structure.reliable ? ["Section boundaries"] : []),
      ...((a.tempo.confidence ?? 1) < 0.5 ? ["Tempo"] : []),
      ...a.warnings,
    ],
    notes: null,
  };

  return dna;
}

function topTraits(obs: Observation[]) {
  return obs
    .filter((o) => o.salience >= 0.7)
    .slice(0, 6)
    .map((o) => ({
      trait: o.text.length > 150 ? `${o.text.slice(0, 147)}...` : o.text,
      why_it_matters: null,
      evidence: [o.id],
      confidence: o.salience,
    }));
}

/**
 * Compose mechanism claims by combining observations that reinforce each other.
 *
 * A single observation is a fact. Two observations that explain one another are
 * an insight, and that is what this product is for.
 */
function buildMechanisms(a: ObjectiveAnalysis, obs: Observation[]): Claim[] {
  const out: Claim[] = [];

  const lift = get(obs, "structure.largest_lift") ?? get(obs, "structure.peak_entry");
  const delayed = get(obs, "structure.delayed_peak");
  const sparseOpen = get(obs, "structure.sparse_opening");

  if (delayed && lift) {
    out.push(
      claim(
        `The arrangement withholds its payoff. The highest-energy section does not arrive until ${formatTime(
          (delayed.evidence.peak_start as number) ?? 0,
        )}, and when it does the step up is large rather than gradual — so the impact comes from contrast against what preceded it, not from the section being loud in absolute terms.`,
        [delayed.id, lift.id],
        0.8,
      ),
    );
  }

  const halfTime = get(obs, "tempo.half_time_feel");
  if (halfTime) {
    out.push(
      claim(
        `The track reads slower than its tempo. The grid is at ${a.tempo.bpm?.toFixed(0)} BPM but the backbeat lands once per bar, so the body tracks roughly ${((a.tempo.bpm ?? 0) / 2).toFixed(0)} BPM. This is what lets it stay unhurried without actually being slow.`,
        [halfTime.id],
        0.8,
      ),
    );
  }

  const widthChange = get(obs, "stereo.width_changes");
  const subHeavy = get(obs, "bass.sub_heavy");
  if (widthChange && lift) {
    out.push(
      claim(
        "Width and level move together rather than independently. Because the stereo picture opens at the same moment the level steps up, the arrival reads as the arrangement getting physically larger, not merely louder.",
        [widthChange.id, lift.id],
        0.75,
      ),
    );
  }

  const staticHarmony = get(obs, "harmony.static");
  if (staticHarmony && (lift || subHeavy)) {
    out.push(
      claim(
        "The harmonic language barely moves, so the sense of change has to come from somewhere else — here it comes from density and low-end weight. That is why the track can feel like it develops without modulating.",
        [staticHarmony.id, (lift ?? subHeavy)!.id],
        0.75,
      ),
    );
  }

  if (sparseOpen && !delayed) {
    out.push(
      claim(
        "The opening sits near the bottom of the track's own energy range, which establishes a floor that everything afterwards is measured against.",
        [sparseOpen.id],
        0.7,
      ),
    );
  }

  const flat = get(obs, "dynamics.flat");
  const compressed = get(obs, "dynamics.heavily_compressed");
  if (flat && compressed) {
    out.push(
      claim(
        "Level is held almost constant and transients are tightly controlled, so the track presents as a continuous wall rather than a series of events. Interest has to come from timbre and texture rather than dynamics.",
        [flat.id, compressed.id],
        0.7,
      ),
    );
  }

  if (out.length === 0) {
    // Never fabricate a mechanism. Fall back to the strongest measured facts.
    return obs.slice(0, 3).map((o) => claim(o.text, [o.id], o.salience * 0.6));
  }
  return out.slice(0, 5);
}

function tensionClaims(obs: Observation[]): Claim[] {
  const out: Claim[] = [];
  for (const id of [
    "structure.sparse_opening",
    "harmony.static",
    "bass.light",
    "dynamics.substantial_quiet",
    "rhythm.sparse_events",
  ]) {
    const o = get(obs, id);
    if (o) out.push(claim(o.text, [o.id], 0.65));
  }
  return out.slice(0, 4);
}

function releaseClaims(obs: Observation[]): Claim[] {
  const out: Claim[] = [];
  for (const id of [
    "structure.largest_lift",
    "structure.peak_entry",
    "bass.sub_heavy",
    "stereo.width_changes",
    "structure.high_contrast",
  ]) {
    const o = get(obs, id);
    if (o) out.push(claim(o.text, [o.id], 0.65));
  }
  return out.slice(0, 4);
}

function buildWhySummary(
  a: ObjectiveAnalysis,
  obs: Observation[],
  userNotes: string[],
): string {
  const parts: string[] = [];
  const delayed = get(obs, "structure.delayed_peak");
  const lift = get(obs, "structure.largest_lift") ?? get(obs, "structure.peak_entry");
  const halfTime = get(obs, "tempo.half_time_feel");
  const staticHarmony = get(obs, "harmony.static");
  const subHeavy = get(obs, "bass.sub_heavy");
  const width = get(obs, "stereo.width_changes");
  const highContrast = get(obs, "structure.high_contrast");

  if (delayed && lift) {
    parts.push(
      `Most of what makes this track work is timing rather than content. The arrangement spends its first stretch below its own energy ceiling and does not reach full weight until ${formatTime(
        (delayed.evidence.peak_start as number) ?? 0,
      )}.`,
    );
  } else if (highContrast) {
    parts.push(
      "The track is built on contrast between sections rather than on continuous development.",
    );
  } else {
    parts.push(
      `This track holds a consistent character throughout, with a ${a.timeline.energy_trajectory_shape ?? "steady"} energy shape.`,
    );
  }

  if (halfTime && a.tempo.bpm) {
    parts.push(
      `It also reads slower than it measures: the grid is ${a.tempo.bpm.toFixed(0)} BPM, but with the backbeat landing once per bar the felt pulse is nearer ${(a.tempo.bpm / 2).toFixed(0)}.`,
    );
  }

  if (staticHarmony) {
    parts.push(
      "The harmony barely moves, which means the sense of arrival is not coming from a chord change — it is coming from arrangement weight.",
    );
  }

  const arrival: string[] = [];
  if (subHeavy) arrival.push("low-end weight");
  if (width) arrival.push("stereo width");
  if (lift) arrival.push("event density");
  if (arrival.length >= 2) {
    parts.push(
      `When ${arrival.slice(0, -1).join(", ")} and ${arrival[arrival.length - 1]} arrive together rather than separately, the payoff feels larger than any one of them would on its own.`,
    );
  }

  if (userNotes.length > 0) {
    parts.push(`You noted: "${userNotes[0]}" — that is worth weighting above anything measured here.`);
  }

  parts.push(
    "(Generated by Soundprint's built-in rules rather than a language model — configure an AI provider for a richer reading.)",
  );

  return parts.join(" ");
}

function buildGuidance(a: ObjectiveAnalysis, obs: Observation[]) {
  const preserve: string[] = [];
  const vary: string[] = [];
  const avoid: string[] = [];

  if (has(obs, "structure.delayed_peak")) preserve.push("Withhold full density until well past the opening");
  if (has(obs, "bass.sub_heavy")) preserve.push("Keep substantial energy below 60 Hz");
  if (has(obs, "harmony.static")) preserve.push("Keep harmonic movement minimal");
  if (has(obs, "tempo.half_time_feel")) preserve.push("Land the backbeat once per bar for a half-time feel");
  if (has(obs, "stereo.width_changes")) preserve.push("Use stereo width as an arrangement device, not a constant");
  if (has(obs, "structure.high_contrast")) preserve.push("Keep a large gap between quietest and loudest sections");
  if (has(obs, "rhythm.low_percussive")) preserve.push("Keep percussion restrained relative to sustained material");
  if (a.tonal.mode === "minor" && !a.tonal.key_ambiguous) preserve.push("Stay in a minor tonality");

  vary.push("Melody and topline — these must be original");
  vary.push("Exact tempo; the feel matters more than the number");
  if (a.tonal.key) vary.push("Specific key; the mode matters more than the pitch centre");
  vary.push("Instrumentation and sound-design choices");

  avoid.push("Reproducing the source melody, lyrics or distinctive progression");
  avoid.push("Imitating a specific artist's voice or identity");
  if (has(obs, "structure.delayed_peak")) avoid.push("Front-loading the arrangement with full density");
  if (has(obs, "dynamics.flat")) avoid.push("Wide dynamic swings, which would break the intended consistency");

  return { preserve: preserve.slice(0, 8), vary: vary.slice(0, 6), avoid: avoid.slice(0, 6) };
}
