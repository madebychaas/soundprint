import { useState } from 'react';
import { useApp } from '../state/store';
import { PROVENANCE_LABEL, SPEC_TABLE, VERIFY_LIST } from '../data/parts';
import { exportNodeGLB } from '../export/exportNodeGLB';
import { IconClose } from './icons';

export function SpecPanel() {
  const set = useApp((s) => s.set);
  const [status, setStatus] = useState<string | null>(null);
  const doExport = async () => {
    setStatus('Preparing…');
    try { await exportNodeGLB(); setStatus('Saved liquid-frequency-node01.glb'); }
    catch (e) { setStatus(`Export failed: ${(e as Error).message}`); }
  };
  return (
    <aside className="drawer specs" aria-label="Technical specification">
      <header>
        <div>
          <p className="panel-kicker">Node 01 · single-node test pad</p>
          <h2>Technical specification</h2>
        </div>
        <button className="icon-btn" onClick={() => set({ panel: 'none' })} aria-label="Close specification"><IconClose /></button>
      </header>
      <p className="fine">An exploratory prototype, not a certified assembly. Nothing here has been measured on hardware.</p>
      <table className="spec-table">
        <tbody>
          {SPEC_TABLE.map((r) => (
            <tr key={r.label}><th>{r.label}</th><td>{r.value}</td><td><span className={`prov ${r.provenance}`}>{PROVENANCE_LABEL[r.provenance]}</span></td></tr>
          ))}
        </tbody>
      </table>

      <p className="panel-kicker gap">What you are looking at</p>
      <ol className="integrity">
        <li><b>Dimension-grounded geometry.</b> The node is built parametrically in millimetres from the reference dimensions above. No CAD file was supplied, so internal features that the reference does not fix are marked <i>proposed</i>.</li>
        <li><b>Conceptual industrial design.</b> The liquid-chrome body, Nodes 02 / 03, the rotary control, proximity window, finishes and glow line are styling studies only.</li>
        <li><b>Simulation and cinematic effects.</b> Lighting, translucency, the cap-lift reveal, signal read-outs, MIDI values and sound are generated by models in this app.</li>
      </ol>

      <p className="panel-kicker gap">Still to verify physically</p>
      <ul className="verify">{VERIFY_LIST.map((v) => <li key={v}>{v}</li>)}</ul>

      <p className="panel-kicker gap">Export</p>
      <div className="row">
        <button className="btn on" onClick={doExport}>Download Node 01 as GLB</button>
        {status && <span className="fine" role="status">{status}</span>}
      </div>
      <p className="fine">Named parts, metres, Y-up, assembled rest pose. A viewing mesh for other 3D tools — not a fabrication-ready CAD file.</p>
    </aside>
  );
}
